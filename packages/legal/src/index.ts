/**
 * `@shagi/legal` — юридические документы продукта: Политика
 * конфиденциальности и Пользовательское соглашение (`05§14`).
 *
 * Зачем отдельный пакет, а не строка в каталоге `@shagi/i18n`: у этих
 * текстов есть то, чего нет ни у одной строки интерфейса — НОМЕР ВЕРСИИ и
 * КОНТРОЛЬНАЯ СУММА, которые спека требует держать неизменяемыми. Это не
 * перевод и не копирайтинг, а версионируемый документ.
 *
 * Тексты не пишутся здесь руками: единственный источник —
 * `docs/legal/*.md`, а `documents.generated.ts` собирается из них скриптом
 * `scripts/build-legal.mjs`. Гейт CI пересобирает файл и падает на любом
 * расхождении, поэтому «поправил в TypeScript, забыл в документе»
 * невозможно по построению.
 *
 * Документы доступны ОФЛАЙН: текст уезжает в бандл приложения как обычная
 * строка, а не подтягивается по сети. Требование прямое — приложение
 * local-first, и показывать «нет соединения» вместо политики
 * конфиденциальности недопустимо.
 */
export { LEGAL_DOCUMENTS } from './documents.generated.js';

/** Идентификатор документа — им же адресуется экран показа. */
export type LegalDocumentId = 'privacy-policy' | 'user-agreement';

export interface LegalDocument {
  readonly id: LegalDocumentId;
  /** Заголовок документа на языке документа. */
  readonly title: string;
  /** Версия из реестра `docs/legal/versions.json`. */
  readonly version: string;
  /** Дата вступления редакции в силу, `YYYY-MM-DD`. */
  readonly effectiveDate: string;
  /** SHA-256 исходного файла — та же, что в реестре версий. */
  readonly sha256: string;
  /** `draft` — документ ждёт реквизитов владельца и не готов к публикации. */
  readonly status: 'draft' | 'final';
  /** Тело документа в Markdown, без front-matter. */
  readonly body: string;
}
