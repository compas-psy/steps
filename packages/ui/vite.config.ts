/**
 * Сборка dev-only харнесса дизайн-системы (`dev/`), НЕ публичного API пакета
 * (`exports` в `package.json` остаётся `./src/index.ts` + два CSS-subpath —
 * харнесс туда не входит). Нужен для E03 «харнесс a11y и визрегрессии»
 * (`.ultraplan/plan.md`, спецификация `docs/spec/SPEC/06_TESTING_ACCEPTANCE.md`
 * §7): единственный способ прогнать axe/Playwright-визрегрессию против
 * реального DOM всех компонентов дизайн-системы — собрать их в одну
 * страницу и открыть её в браузере, `packages/ui` сам по себе — не
 * приложение и ничего не рендерит.
 *
 * Харнесс не подключается ни к `apps/web`, ни к какой-либо сборке продукта:
 * он не нарушает инвариант «apps/* — только оболочки, ни одного экрана»
 * (ТЗ §3) именно потому, что живёт в `packages/ui`, а не в `apps/*` — это
 * внутренний тестовый инструмент пакета компонентов, не продуктовый экран.
 */
import react from '@vitejs/plugin-react';
import { defineConfig } from 'vite';

export default defineConfig({
  root: 'dev',
  plugins: [react()],
  build: {
    // `dist`, не `dev-dist` — единственная правка этого файла в пакете
    // работ E03 «харнесс a11y и визрегрессии»: корневой `.gitignore` и
    // `.oxlintrc.json` (`ignorePatterns: ["**/dist/**", ...]`) уже держат
    // паттерн под это имя (та же причина, что у `apps/web` — сборка веба).
    // Собственное имя каталога сборки харнесса иначе пришлось бы отдельно
    // заводить в обоих местах вне разрешённой территории этого пакета
    // работ, а `dist` — уже готовый, никем не занятый (в `packages/ui` его
    // не было) и корректно исключённый вариант.
    outDir: '../dist',
    target: 'es2023',
  },
});
