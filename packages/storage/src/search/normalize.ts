/**
 * Нормализация строки для поиска (`01§15`, конспект §7 «Ranking»):
 * Unicode NFKC, регистронезависимо, `ё`=`е` **только для сопоставления в
 * поиске**. Это НЕ то же самое, что нормализация `Label.normalizedName`
 * (уникальность меток, `02§2` п.24) — там `ё`≠`е` (задание пакета работ
 * E02.3, «Чего делать нельзя»): две метки «Ёлки» и «Елки» обязаны остаться
 * разными сущностями, но запрос «елки» обязан находить обе. Поэтому эта
 * функция живёт здесь, в `search/`, а не переиспользует нормализацию меток
 * из `@shagi/core`/`memory` — они решают разные задачи из разных мест ТЗ.
 */

const YO_TO_YE = /ё/g;

/**
 * Приводит строку к форме, пригодной для сравнения в поиске. Порядок шагов
 * важен: `trim` убирает случайные пробелы по краям поля ввода (не описано
 * в `01§15` буквально, но не противоречит ему — обычная гигиена
 * поискового UX, не отдельное правило ранжирования); `normalize('NFKC')`
 * приводит совместимые представления Unicode к одной форме; `toLowerCase()`
 * попутно переводит `Ё`→`ё`, поэтому единственная явная замена `ё`→`е`
 * ниже покрывает оба регистра.
 */
export function normalizeForSearch(input: string): string {
  return input.trim().normalize('NFKC').toLowerCase().replace(YO_TO_YE, 'е');
}

/**
 * Токенизация нормализованной строки для «title token»-совпадений (`01§15`
 * п.3): разбиение по границам не-буквенно-цифровых символов, с поддержкой
 * кириллицы и латиницы через Unicode property escapes (`\p{L}`, `\p{N}`,
 * флаг `u`) — обычный `\w` в JS видит только ASCII-буквы и молча ломает
 * русский текст.
 */
export function tokenizeForSearch(normalized: string): readonly string[] {
  if (normalized.length === 0) return [];
  return normalized.split(/[^\p{L}\p{N}]+/u).filter((token) => token.length > 0);
}
