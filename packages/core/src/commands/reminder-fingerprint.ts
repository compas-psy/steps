import type { Reminder } from '../entities/reminder.js';

/**
 * Отпечаток ЖЕЛАЕМОГО расписания одного напоминания на момент последней
 * записи (`kind|firesAt|enabled|title`) — синхронизируемый факт "как, по
 * мнению домена, должно выглядеть это напоминание", ничего больше.
 *
 * ВАЖНО (Task A6, третья и финальная редакция дизайна reconciliation —
 * владелец дважды отклонял более ранние черновики до единой строчки кода,
 * разбор обоих отклонённых вариантов в бриф-файле `task-A6-brief.md`, здесь
 * не повторяется): это поле НИКОГДА не читается сравнением в
 * `applyReconciliation` (`@shagi/app`, `reminder-reconciliation.ts`).
 * Персистентный снимок желаемого сам может устареть точно так же, как
 * устаревало старое id-only сравнение (переименование задачи ничего в этом
 * поле задним числом не пересчитывает) — поэтому reconciliation каждый
 * прогон вычисляет желаемые `title`/момент срабатывания ЖИВЬЁМ (тот же
 * `findById` задачи, что уже делает ради проверки её активности) и
 * сравнивает их с ЖИВЫМ снимком `NotificationSchedulerPort.listScheduled()`,
 * а не с тем, что когда-то было записано сюда.
 *
 * Это поле — НЕ доказательство того, что нативный планировщик КАКОГО-ЛИБО
 * устройства соответствует этому значению. Не использовать его для такого
 * вывода.
 *
 * Более ранний (отклонённый) дизайн предлагал писать сюда значение ПОСЛЕ
 * успешного `schedule()` — "применённое" состояние. Владелец отклонил: у
 * `Reminder` нет per-field HLC (`REMINDERS_TABLE` без `clocks`), а
 * `writeReminder` (`reminder-write.ts`) кладёт ВСЮ строку в
 * `SyncOutboxEntry.patchJson` при каждой записи — факт "успешно применено к
 * AlarmManager ЭТОГО устройства" по природе локален, запись его в
 * синхронизируемое поле позволила бы устройству A переписать веру
 * устройства B в СОБСТВЕННОЕ состояние ОС. Ложная идемпотентность хуже
 * отсутствующей — ровно тот баг, ради починки которого существует эта
 * задача.
 *
 * `title` — новый параметр (было отсутствовал, задокументированный открытый
 * пробел прежней версии этого комментария: переименование задачи никак не
 * отражалось). Теперь честно: смена заголовка меняет отпечаток здесь, а
 * reconciliation реально ловит смену заголовка сравнением ЖИВОГО значения
 * (не персистентного снимка) с тем, что видно в `listScheduled()`.
 *
 * Не криптографический хэш — отпечаток сравнивается только с самим собой
 * (предыдущим значением того же напоминания), коллизии между РАЗНЫМИ
 * напоминаниями не имеют значения (id напоминания — отдельное поле, любое
 * потенциальное сравнение шло бы по id, отпечаток только внутри одного id).
 */
export function computeReminderFingerprint(
  reminder: Pick<Reminder, 'kind' | 'localRuleJson' | 'enabled'>,
  title: string,
): string {
  const firesAt =
    typeof reminder.localRuleJson.firesAt === 'string' ? reminder.localRuleJson.firesAt : '';
  return `${reminder.kind}|${firesAt}|${reminder.enabled ? '1' : '0'}|${title}`;
}
