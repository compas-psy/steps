import type { Reminder } from '../entities/reminder.js';

/**
 * Отпечаток желаемого расписания одного напоминания (`02§14`
 * "notification reconciliation": каждый запуск/wake сравнивает отпечатки
 * желаемого с тем, что реально запланировано на ОС, отменяет лишнее и
 * досоздаёт недостающее).
 *
 * Меняется тогда и только тогда, когда меняется то, что ДОЛЖНО произойти
 * в системном планировщике: `kind` (разный кулдаун/логика доставки),
 * `localRuleJson.firesAt` (момент срабатывания — общее поле всех трёх
 * `kind`, см. `reminder-explicit.ts`) и `enabled` (выключенное напоминание
 * не должно быть запланировано вовсе). `title`/`taskId` в этот отпечаток НЕ
 * входят — но это НЕ значит, что смена заголовка задачи безопасна для уже
 * запланированного напоминания.
 *
 * ИСПРАВЛЕНО (было ошибочное утверждение): `tauri-plugin-notification`
 * 2.4.0 НЕ перечитывает title/body в момент срабатывания и НЕ читает их из
 * SQLite — заголовок замораживается в `android.app.Notification`
 * (Parcelable) уже на этапе `schedule()`/`show()` и воспроизводится
 * буквально тем же байтовым Parcelable при срабатывании alarm
 * (`TimedNotificationPublisher.onReceive`, проверено по исходнику плагина
 * 2.4.0). Никакого рантайм-чтения из приложения/БД плагин не делает —
 * ни при срабатывании, ни при boot-restore.
 *
 * ОТКРЫТЫЙ ПРОБЕЛ (не закрыт этим полем, зафиксировано для Фазы B):
 * переименование задачи ПОСЛЕ того, как для неё уже запланировано
 * напоминание, сейчас НИЧЕМ не перепланирует alarm — `reconcileReminder-
 * Schedule`/`ForTask` (Task A3) намеренно не диффит содержимое, только
 * id-присутствие (см. PRE-FLIGHT RULING там же), а переименование задачи не
 * меняет ни `Reminder.enabled`, ни её id. Добавление `title` СЮДА без
 * механизма, который эту разницу реально считывает и вызывает `schedule()`
 * заново, было бы косметикой, а не фиксом — отпечаток тогда менялся бы, но
 * никто бы его не сравнивал. Нужен отдельный шаг: реконсиляция после
 * переименования задачи + отказ от чистого id-presence idempotency в пользу
 * учёта контента. См. ledger `.superpowers/sdd/.../progress.md`.
 *
 * Не криптографический хэш — отпечаток сравнивается только с самим собой
 * (предыдущим значением того же напоминания), коллизии между РАЗНЫМИ
 * напоминаниями не имеют значения (id напоминания — отдельное поле,
 * reconciliation сравнивает по id, отпечаток только внутри одного id).
 */
export function computeReminderFingerprint(
  reminder: Pick<Reminder, 'kind' | 'localRuleJson' | 'enabled'>,
): string {
  const firesAt =
    typeof reminder.localRuleJson.firesAt === 'string' ? reminder.localRuleJson.firesAt : '';
  return `${reminder.kind}|${firesAt}|${reminder.enabled ? '1' : '0'}`;
}
