import { Temporal } from '@js-temporal/polyfill';

import type { Task } from '../entities/task.js';
import { makePriority } from '../values.js';
import { classifyTaskForToday } from './today-classification.js';

/**
 * Отбор для пяти «Системных фильтров» (`01§16` «System filters R1», раздел
 * прочитан целиком): "Без даты / P1 Критичные / Не по плану / Просрочен
 * срок / Повторяющиеся. Read-only predefined." Пакет работ E12.3.
 *
 * --- Почему это селектор `@shagi/core`, а не логика внутри экрана ---------
 *
 * Тот же принцип, что `selectPlanAgenda`/`selectTodayTasks`: правило отбора
 * — домен, не UI. Здесь оно особенно важно для двух из пяти фильтров (см.
 * следующий блок) — не размазывать копию правила "просрочена" по разным
 * файлам `packages/app`.
 *
 * --- «Не по плану» / «Просрочен срок»: переиспользование, не повторное
 * изобретение ------------------------------------------------------------
 *
 * Задание пакета работ прямо требует не переизобретать правило "просрочена
 * по плану"/"просрочен дедлайн" второй раз, если оно уже выражено в
 * `today-classification.ts`. Оно уже выражено — `classifyTaskForToday`
 * (см. её заголовок) решает ИМЕННО эту классификацию, с ИМЕННО той же
 * семантикой, которая нужна двум из пяти фильтров:
 *  - "Не по плану" — активная задача, чей `plannedDate` в прошлом.
 *  - "Просрочен срок" — активная задача, чей эффективный дедлайн
 *    (`effectiveDeadlineDateTime`, дата без времени = конец локальных
 *    суток) уже прошёл.
 *
 * `classifyTaskForToday` уже реализует ровно эти два условия и, что важнее,
 * уже решает конфликт между ними: задача одновременно с просроченным планом
 * И просроченным дедлайном по прецедансу `01§6` — это `missed_deadline`, не
 * `missed_plan` (дедлайн проверяется первым). Фильтры этого пакета работ
 * применяют ТУ ЖЕ функцию, поэтому наследуют тот же прецеденс без отдельной
 * проверки: `groups.missedPlan` и `groups.missedDeadline` взаимно
 * исключают такую задачу так же, как соответствующие группы Today —
 * не потому что здесь есть об этом отдельная строка кода, а потому что под
 * капотом ровно один вызов `classifyTaskForToday` на задачу, и она
 * структурно не может вернуть два разных результата сразу (см. заголовок
 * `today-classification.ts`, "No duplicates" — свойство формы функции).
 *
 * Альтернатива (переписать оба условия здесь заново, без общего прецеденса
 * между собой) была отвергнута: она завела бы вторую копию всё того же
 * решения "чей дедлайн главнее" и рисковала бы разойтись с Today, если
 * правило `01§6` когда-нибудь уточнится в одном месте, но не в другом.
 *
 * Три оставшихся фильтра ("Без даты"/"P1"/"Повторяющиеся") у Today групп
 * не имеют аналога вовсе — `classifyTaskForToday` их не знает (задача без
 * единой даты никогда не появляется на Today, см. её заголовок), поэтому
 * они выражены здесь как прямые независимые предикаты поверх полей задачи
 * — переиспользовать нечего, эти условия нигде в дереве пакетов раньше не
 * существовали.
 *
 * --- Пять фильтров НЕ взаимоисключающие между собой -----------------------
 *
 * В отличие от `TodayGroup` (одна задача — ровно одна группа, `01§6`),
 * `01§16` не требует такого свойства от системных фильтров — это пять
 * НЕЗАВИСИМЫХ предикатов, каждый проверяется отдельно на каждой задаче.
 * Критичная задача без единой даты легитимно попадает и в "Без даты", и в
 * "P1" одновременно (оба фильтра, если открыты по очереди, покажут её) —
 * см. тест "смешанный набор". Единственная пара, что взаимоисключает друг
 * друга — "Не по плану"/"Просрочен срок" — исключает не потому, что это
 * фильтры, а потому что оба транзитивно наследуют прецеденс
 * `classifyTaskForToday` (см. блок выше), это следствие переиспользования,
 * не отдельное правило "фильтры не пересекаются".
 *
 * --- Чистая функция, явный вход "сейчас" (CLAUDE.md «Время») --------------
 *
 * Не ходит в хранилище (тот же приём, что `selectPlanAgenda`) — список уже
 * загруженных активных задач передаёт вызывающий код (`packages/app`,
 * `Search.tsx`, см. её заголовок за деталями места в UI). `now` —
 * `Temporal.PlainDateTime`, тот же тип, что принимает
 * `classifyTaskForToday` (нужна точность до времени суток для дедлайна, не
 * только дата) — функция не читает системные часы сама, тестируема без
 * моков времени.
 *
 * --- Все пять групп считаются за один проход ------------------------------
 *
 * Аналог `selectTodayTasks`: один проход по входному массиву, один вызов
 * `classifyTaskForToday` на задачу (не два — не отдельно "проверить
 * missedPlan", отдельно "проверить missedDeadline"), результат раскладывается
 * сразу в оба соответствующих бакета через `switch`. Экран получает готовые
 * пять списков разом и просто индексирует по выбранному id при переключении
 * фильтра — переключение не требует повторного вызова этой функции.
 */
export type SystemFilterId = 'noDate' | 'p1' | 'missedPlan' | 'missedDeadline' | 'recurring';

/** Порядок — буквально порядок перечисления `01§16`: "Без даты / P1
 * Критичные / Не по плану / Просрочен срок / Повторяющиеся". `packages/app`
 * рендерит фильтры в этом порядке, не изобретая свой. */
export const SYSTEM_FILTER_IDS: readonly SystemFilterId[] = [
  'noDate',
  'p1',
  'missedPlan',
  'missedDeadline',
  'recurring',
];

export type SystemFilterGroups = Record<SystemFilterId, readonly Task[]>;

const CRITICAL_PRIORITY = makePriority(1);

function compareByRank(a: Task, b: Task): number {
  if (a.rank < b.rank) return -1;
  if (a.rank > b.rank) return 1;
  return 0;
}

/**
 * Собирает пять групп системных фильтров из уже загруженного списка задач —
 * см. заголовок файла за полным разбором решений.
 *
 * `status === 'completed'` отфильтровывается защитой в глубину (тот же
 * приём, что первая проверка `classifyTaskForToday`/`selectPlanAgenda`):
 * вызывающий код должен передавать только активные задачи, но функция не
 * падает и не включает завершённую ни в один из пяти списков, если фильтр
 * выше по стеку однажды ошибётся — "Read-only predefined" (`01§16`)
 * фильтры об активных задачах, ни один из пяти не имеет смысла для
 * завершённой.
 *
 * Сортировка внутри каждой группы — `rank` (тот же выбор, что
 * `missed_deadline`/`missed_plan`/`focus` у `selectTodayTasks`, см. её
 * заголовок за обоснованием): `01§16` не задаёт критерий сортировки внутри
 * фильтра, а `rank` — единственный существующий ручной порядок задачи,
 * применённый одинаково ко всем пяти, а не только к двум переиспользующим
 * Today-классификацию.
 */
export function selectSystemFilters(
  tasks: readonly Task[],
  now: Temporal.PlainDateTime,
): SystemFilterGroups {
  const buckets: Record<SystemFilterId, Task[]> = {
    noDate: [],
    p1: [],
    missedPlan: [],
    missedDeadline: [],
    recurring: [],
  };

  for (const task of tasks) {
    if (task.status === 'completed') continue;

    if (task.plannedDate === null && task.deadlineDate === null) {
      buckets.noDate.push(task);
    }
    if (task.priority === CRITICAL_PRIORITY) {
      buckets.p1.push(task);
    }
    if (task.seriesId !== null) {
      buckets.recurring.push(task);
    }

    // Один вызов на задачу — см. заголовок файла, блок «Все пять групп
    // считаются за один проход».
    const todayGroup = classifyTaskForToday(task, now);
    if (todayGroup === 'missed_plan') {
      buckets.missedPlan.push(task);
    } else if (todayGroup === 'missed_deadline') {
      buckets.missedDeadline.push(task);
    }
  }

  return {
    noDate: buckets.noDate.toSorted(compareByRank),
    p1: buckets.p1.toSorted(compareByRank),
    missedPlan: buckets.missedPlan.toSorted(compareByRank),
    missedDeadline: buckets.missedDeadline.toSorted(compareByRank),
    recurring: buckets.recurring.toSorted(compareByRank),
  };
}
