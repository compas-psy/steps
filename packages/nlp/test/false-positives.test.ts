import { describe, expect, it } from 'vitest';

import { parseQuickAdd } from '../src/parse.js';
import { MONDAY } from './helpers.js';

/** Текст, похожий на команду грамматики, но ей не являющийся — "никогда не
 * угадывать молча" работает в обе стороны: не только не додумывать
 * значение, но и не видеть служебный токен там, где его нет. */
describe('ложные срабатывания', () => {
  it.each([
    'Перейти через дорогу',
    'Пойти в магазин',
    'Сходить до свидания с другом',
    'Ждать до последнего',
    'Купить 5 яблок',
    'Обсудить часть проекта',
    'Идти в течение дня',
    'Проверить минутку',
    'Список дел на неделе',
    'Взять номер пятнадцать',
    'Написать код на React',
    'Урок номер 5',
    'Погулять денек',
    'Отметить встречу',
    'Сделать через силу',
    'Купить хеш-тег без решётки',
    'Написать письмо user@example.com себе',
    'Проверить почту в 25',
    'Задача каждое воскресение', // опечатка вместо "воскресенье" — не матчится
  ])('"%s" — ни одного чипа', (text) => {
    const r = parseQuickAdd({ text, now: MONDAY });
    expect(r.chips).toHaveLength(0);
  });
});
