/**
 * Форма golden-корпуса (`01§4`: "Golden corpus: >=800 examples"; в этом
 * пакете работ — 250-300, задел на расширение описан в
 * `test/golden-corpus.test.ts`). Данные, а не код: следующий пакет работ
 * расширяет корпус до 800+, просто дописывая объекты в массив
 * `GOLDEN_CORPUS`, не трогая раннер.
 *
 * Два уровня строгости проверки намеренно:
 * - `expectedCategories` (обязательное, мультимножество) — какие категории
 *   ПРИНЯТЫ, сравнивается без учёта порядка, но с учётом количества
 *   (например, два `label` в одном тексте — `['label', 'label']`). Это
 *   основная, всегда проверяемая часть каждого кейса, включая ложные
 *   срабатывания (`[]` — ничего не должно было распознаться).
 * - `expectedTitle` (опциональное) — заголовок после вычистки; не всегда
 *   задан, потому что для части кейсов интересна именно категория, а не
 *   точный остаток текста.
 * - `expectedValues` (опциональное, точечная проверка) — вычисленные
 *   значения избранных кейсов (сериализованные в строки через
 *   `Temporal`/`.toString()`), где важна не просто категория, а точный
 *   результат вычисления (например, разница "в пятницу"/"в следующую
 *   пятницу"). Не на каждый кейс — этого намеренно не требовалось (см.
 *   отчёт пакета работ): такие случаи уже покрыты построчными unit-
 *   тестами по категориям с точными `Temporal`-сравнениями; здесь корпус
 *   нужен прежде всего для широты (много реалистичных фраз), а не для
 *   дублирования той же точности на каждой из трёх сотен строк.
 */

import type { ChipCategory } from '../types.js';

export interface GoldenCaseExpectedValue {
  readonly category: ChipCategory;
  /** Строковое представление вычисленного значения для этой категории —
   * `date`/`weekday`: ISO-дата; `time`: ISO-время; `duration`: минуты
   * строкой; `priority`: 1-4 строкой; `project`/`label`: имя. */
  readonly value: string;
}

export interface GoldenCase {
  readonly id: string;
  readonly text: string;
  readonly now: { readonly date: string; readonly time: string };
  readonly inherited?: { readonly date: string };
  readonly expectedCategories: readonly ChipCategory[];
  readonly expectedTitle?: string;
  /** Читаемость заголовка после вычистки (решение `?10`) — задаётся для
   * кейсов, где текст целиком состоит из служебных токенов и пунктуации. */
  readonly expectedReadable?: boolean;
  readonly expectedValues?: readonly GoldenCaseExpectedValue[];
  /** Почему кейс интересен — какая реалистичная фраза Quick Add за ним
   * стоит, какую границу/неоднозначность он покрывает. */
  readonly note: string;
}
