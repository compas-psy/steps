#!/usr/bin/env bash
# Создать ПОСТОЯННЫЙ ключ подписи Android — один раз на всю жизнь продукта.
#
# ── Почему это делается руками, а не в CI ───────────────────────────────────
#
# Ключ — это личность приложения. Android ставит обновление поверх только если
# подпись совпала: сменили ключ — и человек с установленным приложением видит
# «Приложение не установлено» без объяснения причины. Восстановить ключ нельзя
# ниоткуда: ни у нас, ни у Google его нет.
#
# Поэтому ключ создаёт владелец продукта на своей машине, кладёт себе в
# надёжное место и отдаёт в GitHub только копию в base64. Скрипт ничего не
# отправляет и ничего не оставляет в репозитории — он печатает то, что нужно
# вставить в секреты, и напоминает, что файл надо сохранить.
#
#   bash scripts/make-android-keystore.sh
#
# Дальше — четыре секрета в Settings → Secrets and variables → Actions:
#   ANDROID_KEYSTORE_BASE64, ANDROID_KEYSTORE_PASSWORD,
#   ANDROID_KEY_ALIAS, ANDROID_KEY_PASSWORD
#
# И одна правка в репозитории — отпечаток SHA-256 (строка ниже, из вывода
# этого скрипта) вписывается в `apps/mobile/EXPECTED_SIGNER.txt`. Пока файл
# пуст, производственная сборка (тег `shagi-v*`, пуш в ветку по умолчанию,
# ручной запуск с явным выбором production) падает на шаге подготовки
# keystore с сообщением «ключ подписи ещё не создан» — это ожидаемо и
# безопасно: разработческие сборки (pull request, чужая ветка) при этом
# продолжают выходить как debug-APK постоянным отладочным ключом
# (apps/mobile/keys/README.md) и в GitHub Release не попадают никогда.
# Подробности и проверки — в шапке `.github/workflows/build-android.yml` и в
# `apps/mobile/scripts/android-release-gate.mjs`.
#
# ЕСЛИ КЛЮЧ УЖЕ СОЗДАН И СЕКРЕТЫ ЗАПОЛНЕНЫ — ЭТОТ СКРИПТ БОЛЬШЕ НЕ ЗАПУСКАЮТ.
# Новый ключ означает новую личность приложения: у всех, кто уже поставил
# ШАГИ, обновление перестанет вставать, и им придётся удалять приложение.
set -euo pipefail

OUT="${1:-$HOME/shagi-release.jks}"
ALIAS="${ANDROID_KEY_ALIAS:-shagi}"
DAYS="${DAYS:-10950}" # 30 лет: Play требует срок действия минимум до 2033 года

if ! command -v keytool >/dev/null 2>&1; then
  echo 'Нужен keytool — он входит в JDK. Поставьте JDK 21 и повторите.' >&2
  exit 1
fi

if [ -e "${OUT}" ]; then
  echo "Файл ${OUT} уже существует." >&2
  echo 'Перезаписывать НЕ буду: если это ваш рабочий ключ, потеря необратима.' >&2
  echo 'Укажите другой путь: bash scripts/make-android-keystore.sh /путь/к/новому.jks' >&2
  exit 1
fi

# ── Ключ не должен лежать рядом с кодом ─────────────────────────────────────
#
# Верный способ отправить его в git одним `git add -A`. Относительный путь
# почти всегда означает «где я сейчас стою», а стоят обычно внутри
# репозитория — поэтому годится только абсолютный путь. Дальше он
# приводится к каноническому виду через `realpath -m` (работает и для
# файла, которого ещё нет — канонизирует существующие родительские
# каталоги, остальное достраивает буквально) и сверяется с корнем
# репозитория этого скрипта: совпадение или вложенность — отказ.
case "${OUT}" in
  /*) : ;;
  *)
    echo "Путь ${OUT} — не абсолютный." >&2
    echo 'Ключ не должен лежать рядом с кодом. Дайте абсолютный путь вне' >&2
    echo 'репозитория, например: bash scripts/make-android-keystore.sh ~/shagi-release.jks' >&2
    exit 1
    ;;
esac

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(git -C "${SCRIPT_DIR}" rev-parse --show-toplevel 2>/dev/null || true)"
if [ -n "${REPO_ROOT}" ]; then
  OUT_ABS="$(realpath -m "${OUT}")"
  case "${OUT_ABS}" in
    "${REPO_ROOT}" | "${REPO_ROOT}"/*)
      echo "Путь ${OUT} указывает внутрь рабочего дерева репозитория (${REPO_ROOT})." >&2
      echo 'Ключ не должен лежать рядом с кодом — выберите путь вне репозитория,' >&2
      echo 'например: bash scripts/make-android-keystore.sh ~/shagi-release.jks' >&2
      exit 1
      ;;
  esac
fi

echo "Создаю ключ: ${OUT}"
echo "Алиас: ${ALIAS}; срок действия: ${DAYS} дней"
echo
echo 'Что спросит keytool — по порядку:'
echo '  1. Пароль хранилища и подтверждение. Придумайте один пароль и на'
echo '     хранилище, и на ключ: файл всё равно один, защищённость та же.'
echo '  2. Имя и фамилия, подразделение, организация, город, край, код страны.'
echo '     Это данные сертификата. Пользователю они не показываются, но'
echo '     меняются только вместе с ключом, то есть никогда. Годится название'
echo '     продукта: ШАГИ / ШАГИ / СИМПАС / город / край / RU.'
echo '  3. «Верно?» — ответьте латинским yes (не «да»).'
echo
echo 'Чтобы не отвечать на вопросы, задайте их заранее одной строкой:'
echo '  DNAME="CN=ШАГИ, O=СИМПАС, C=RU" bash scripts/make-android-keystore.sh'
echo

args=(
  -genkeypair
  -v
  -keystore "${OUT}"
  -alias "${ALIAS}"
  -keyalg RSA
  -keysize 4096
  -validity "${DAYS}"
)
# Через массив, а не через подстановку в строку: в DNAME есть пробелы, и
# `${DNAME:+-dname "$DNAME"}` разорвало бы его на несколько аргументов.
if [ -n "${DNAME:-}" ]; then args+=(-dname "${DNAME}"); fi

keytool "${args[@]}"

echo
echo '── Отпечаток ключа ─────────────────────────────────────────────────────'
echo 'Пароль спросят ещё раз: прочитать ключ иначе нельзя. Введите тот же.'
# Без пароля keytool печатает не отпечаток, а блок «WARNING WARNING WARNING»
# про непроверенную целостность — и человек читает его как поломку ключа.
# Поэтому шум глушим, а отсутствие отпечатка называем своим именем.
if ! keytool -list -v -keystore "${OUT}" -alias "${ALIAS}" 2>/dev/null |
  grep -E 'SHA1:|SHA256:'; then
  echo 'Отпечаток не показан — пароль не введён. Ключ при этом создан и годен.'
  echo "Посмотреть позже: keytool -list -v -keystore ${OUT} -alias ${ALIAS}"
fi

echo
echo '── ANDROID_KEYSTORE_BASE64 ─────────────────────────────────────────────'
echo 'Скопируйте строку целиком, без переносов:'
echo
base64 -w0 "${OUT}" 2>/dev/null || base64 "${OUT}" | tr -d '\n'
echo
echo
echo '── Что дальше ──────────────────────────────────────────────────────────'
echo "1. Сохраните ${OUT} в надёжном месте (менеджер паролей, сейф)."
echo '   Потеря ключа = невозможность выпускать обновления. Навсегда.'
echo '2. В GitHub → Settings → Secrets and variables → Actions создайте:'
echo '     ANDROID_KEYSTORE_BASE64   — строка выше'
echo "     ANDROID_KEY_ALIAS         — ${ALIAS}"
echo '     ANDROID_KEYSTORE_PASSWORD — пароль, который вы задали'
echo '     ANDROID_KEY_PASSWORD      — он же'
echo '3. Впишите отпечаток SHA-256 из блока выше единственной'
echo '   незакомментированной строкой в apps/mobile/EXPECTED_SIGNER.txt и'
echo '   закоммитьте эту правку — до неё производственная сборка падает'
echo '   специально (см. комментарий в самом файле).'
echo '4. Следующая сборка Android выйдет подписанной этим ключом, и все'
echo '   дальнейшие обновления встанут поверх неё.'
echo
echo 'Отпечаток выше сохраните тоже: по нему сверяется, что обновление'
echo 'подписано тем же ключом, что и установленная сборка — смена ключа'
echo 'обязана быть громкой (упавшей сборкой), а не тихой деградацией.'
